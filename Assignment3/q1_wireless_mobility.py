"""Q1: Wireless architecture and mobility handoff simulation."""
import numpy as np
import matplotlib.pyplot as plt
from common import savefig

SEEDS=range(8)
PACKETS_PER_SECOND=50
DURATION=300
HANDOFFS=[(0.10,0.5),(0.30,0.2),(0.50,0.1)] # handoff rate per second, interruption seconds
rows=[]
for rate, interruption in HANDOFFS:
    lost=[]
    for seed in SEEDS:
        rng=np.random.default_rng(seed)
        events=rng.poisson(rate*DURATION)
        # Count packets generated during each handoff gap.
        gaps=rng.uniform(0,DURATION,events)
        count=sum(int(round(PACKETS_PER_SECOND*interruption)) for _ in gaps)
        lost.append(count)
    rows.append(np.mean(lost))
    print(f"Handoff rate={rate:.2f}/s, interruption={interruption:.2f}s, "
          f"mean packets lost={np.mean(lost):.1f}")
plt.figure(figsize=(7,4))
plt.bar([f"{r:.1f}/s" for r,_ in HANDOFFS],rows)
plt.xlabel("Handoff event rate"); plt.ylabel("Packets lost in 300 s")
plt.title("Q1 – Packet loss caused by handoff interruption")
savefig("q1_handoff_loss.png")
